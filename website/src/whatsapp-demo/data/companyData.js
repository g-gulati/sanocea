export function getChannelLogo(channelId, channelName = '') {
  const cid = (channelId || '').toLowerCase()
  const lower = (channelName || '').toLowerCase()

  // 1. Strict SANOCEA Neutral System Icons (Never map to Shopify or Amazon)
  if (cid === 'production-web' || cid === 'globe' || cid === 'web' || lower.includes('production web') || lower.includes('sanocea.com')) {
    return CHANNEL_LOGOS['production-web']
  }
  if (cid === 'ai-crawlers' || cid === 'bot' || cid === 'crawler' || lower.includes('ai crawler') || lower.includes('ai discovery') || lower.includes('gptbot') || lower.includes('claudebot') || lower.includes('perplexity')) {
    return CHANNEL_LOGOS['ai-crawlers']
  }

  // 2. Direct ID Match
  if (channelId && CHANNEL_LOGOS[channelId]) return CHANNEL_LOGOS[channelId]

  // 3. Name-based Match for Connected Commerce Channels Only
  if (lower.includes('blinkit')) return CHANNEL_LOGOS.blinkit
  if (lower.includes('amazon')) return CHANNEL_LOGOS.amazon
  if (lower.includes('shopify')) return CHANNEL_LOGOS.shopify
  if (lower.includes('bigcommerce') || lower.includes('waaree.com') || lower.includes('d2c')) return CHANNEL_LOGOS.bigcommerce
  if (lower.includes('sufin') || lower.includes('l&t')) return CHANNEL_LOGOS['lnt-sufin']
  if (lower.includes('moglix')) return CHANNEL_LOGOS.moglix
  if (lower.includes('swiggy') || lower.includes('instamart')) return CHANNEL_LOGOS.instamart
  if (lower.includes('flipkart')) return CHANNEL_LOGOS.flipkart
  if (lower.includes('woo')) return CHANNEL_LOGOS.woocommerce
  if (lower.includes('etsy')) return CHANNEL_LOGOS.etsy
  if (lower.includes('google')) return CHANNEL_LOGOS.google
  if (lower.includes('jiomart')) return CHANNEL_LOGOS.jiomart
  if (lower.includes('meesho')) return CHANNEL_LOGOS.meesho
  if (lower.includes('myntra')) return CHANNEL_LOGOS.myntra
  if (lower.includes('nykaa')) return CHANNEL_LOGOS.nykaa
  return null
}

